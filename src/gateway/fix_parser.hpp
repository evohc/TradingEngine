/*
FIX (Financical Information eXchange) is a standard for finance industry.
Simply its a string of pipe (SOH byte) separated key-value pairs. Each key is a unique
number that represents a specific piece of trading information, and the value
is the actual data.  Unlike other protocols e.g. NasDaq ITCH which is a fixed
width binary protocol which allows for bytes level casting FIX is a variable
length text protocol, so fields grow/shrink so some level of parsng is required.

e.g.

Tag   Name           Value               Meaning
8     BeginString    FIX.4.4             Protocol version
9     BodyLength     122                 Message size, total number of bytes from the start of tag 35 to the delimiter right before tag 10
35    MsgType        D                   Message Type: e.g. D=New Order, F=Cancel
49    SenderCompID   Sender              Unique ID of the originater the trade
56    TargetCompID   Receiver            Unique ID of the receiver this order
34    MsgSeqNum      101                 A sequential counter used to track missing messages and prevent connection drops or duplicate orders
52    SendingTime    20260702-12:00:00   UTC timestamp
11    ClOrdID        1234678910          Client Order ID: A unique string generated by the sender to track this specific order lifecycle
21    HandlInst      1,                  Handling Instructions
55    Symbol         SYM_4               The ticker symbol of the financial instrument being traded
54    Side           1                   1=Buy, 2=Sell
38    OrderQty       1000                The total number of shares, contracts, or units being requested
40    OrdType        2                   Order Type
44    Price          180.00              Price
10    CheckSum       142                 CheckSum
*/

#pragma once
#include "../common/fixed_string.hpp"
#include <cstdint>
#include <string_view>

enum class FixMsgType : char {
    Logon = 'A',
    Logout = '5',
    NewSingleOrder = 'D',
    Unknown = '0',
};

enum class Side : char { // override type to char = 1 byte v 4 and its a char in FIX as well
    Buy = '1',
    Sell = '2',
    Unknown = '0'
};

//only fields neccessary for matching engine.
struct ParsedFixFields {
    FixMsgType msg_type{FixMsgType::Unknown};
    common::FixedString<32> client_order_id;
    common::FixedString<16> symbol;
    common::FixedString<32> sender_comp_id;
    common::FixedString<32> target_comp_id;
    double price{0.0};
    uint64_t quantity{0};
    Side side{Side::Unknown};
    uint32_t msg_seq_num{0};

    constexpr void reset() noexcept {
        msg_type = FixMsgType::Unknown;
        client_order_id.clear();
        symbol.clear();
        sender_comp_id.clear();
        target_comp_id.clear();
        price = 0.0;
        quantity = 0;
        side = Side::Unknown;
        msg_seq_num = 0;
    }
};

[[nodiscard]] bool parse_fix_message(std::string_view raw_frame, ParsedFixFields& out_fields) noexcept;